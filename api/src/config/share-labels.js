function base(lang) {
  return String(lang || 'en')
    .toLowerCase()
    .split(/[-_]/)[0];
}

// True only for the ten canonical philosophical verdicts. News rows carry a
// media type in `classification`, which is not a verdict and must not be
// pasted into a card as if it were one.
export function isVerdict(classification) {
  return Boolean(classification && VERDICTS.en[classification]);
}

// The verdict in `lang`, falling back to English. Empty when not a verdict.
export function verdictLabel(classification, lang) {
  if (!isVerdict(classification)) return '';
  const table = VERDICTS[base(lang)] || VERDICTS.en;
  return table[classification] || VERDICTS.en[classification];
}

export function panelLabel(lang) {
  return PANEL[base(lang)] || PANEL.en;
}

export function debateLabel(lang) {
  return DEBATE[base(lang)] || DEBATE.en;
}
